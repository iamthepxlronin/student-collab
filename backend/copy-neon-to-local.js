require('dotenv').config();
const { Pool } = require('pg');

const neon = new Pool({ connectionString: process.env.DATABASE_URL });
const local = new Pool({ connectionString: process.env.LOCAL_DATABASE_URL });

// order matters: tables with foreign keys come after the tables they point to
const TABLES = ['users', 'collaboration_posts', 'applications'];

async function run() {
  // start clean so the script can be safely re-run
  for (const t of [...TABLES].reverse()) {
    await local.query(`DROP TABLE IF EXISTS "${t}" CASCADE`);
  }
  const sequences = [];

  for (const table of TABLES) {
    // 1. read the table's structure from Neon
    const { rows: cols } = await neon.query(
      `SELECT column_name, data_type, udt_name, character_maximum_length,
              is_nullable, column_default, is_identity
       FROM information_schema.columns
       WHERE table_schema = 'public' AND table_name = $1
       ORDER BY ordinal_position`, [table]);

    const defs = [];
    for (const c of cols) {
      let type = c.data_type;
      if (type === 'character varying') {
        type = c.character_maximum_length ? `varchar(${c.character_maximum_length})` : 'varchar';
      }
      if (type === 'ARRAY') type = c.udt_name.replace(/^_/, '') + '[]';

      let def = `"${c.column_name}" ${type}`;
      if (c.column_default) {
        def += ` DEFAULT ${c.column_default}`;
        const m = c.column_default.match(/nextval\('([^']+)'::regclass\)/);
        if (m) {
          const seq = m[1].replace(/^public\./, '').replace(/"/g, '');
          await local.query(`CREATE SEQUENCE IF NOT EXISTS "${seq}"`);
          sequences.push({ seq, table, col: c.column_name });
        }
      } else if (c.is_identity === 'YES') {
        def += ' GENERATED BY DEFAULT AS IDENTITY';
      }
      if (c.is_nullable === 'NO') def += ' NOT NULL';
      defs.push(def);
    }

    // primary key, unique, check and foreign key rules
    const { rows: cons } = await neon.query(
      `SELECT pg_get_constraintdef(oid) AS def FROM pg_constraint
       WHERE conrelid = $1::regclass AND contype IN ('p','u','c','f')
       ORDER BY CASE contype WHEN 'p' THEN 1 WHEN 'u' THEN 2 WHEN 'c' THEN 3 ELSE 4 END`,
      [`public.${table}`]);
    cons.forEach(k => defs.push(k.def));

    // 2. build the same table locally
    await local.query(`CREATE TABLE "${table}" (\n  ${defs.join(',\n  ')}\n)`);

    // 3. copy the rows across
    const { rows } = await neon.query(`SELECT * FROM "${table}"`);
    for (const row of rows) {
      const keys = Object.keys(row);
      await local.query(
        `INSERT INTO "${table}" (${keys.map(k => `"${k}"`).join(', ')})
         VALUES (${keys.map((_, i) => `$${i + 1}`).join(', ')})`,
        keys.map(k => row[k]));
    }
    console.log(`${table}: copied ${rows.length} rows`);
  }

  // 4. make auto-numbering continue after the highest copied id
  for (const { seq, table, col } of sequences) {
    await local.query(
      `SELECT setval($1, COALESCE((SELECT MAX("${col}") FROM "${table}"), 0) + 1, false)`, [seq]);
  }
  console.log('Done.');
}

run()
  .catch(e => console.error('Failed:', e.message))
  .finally(() => Promise.all([neon.end(), local.end()]));